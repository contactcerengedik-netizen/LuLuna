/// Yerleşik glyph path seti — A–Z, a–z, 0–9 (normalize 0–1).
/// Font parse yok; öğretmen kelimesi → path dizisi.
abstract final class GlyphPaths {
  static List<List<Offset>>? forChar(String ch) {
    if (ch.isEmpty) return null;
    final c = ch.length == 1 ? ch : ch[0];
    return _glyphs[c] ?? _glyphs[c.toUpperCase()];
  }

  /// Tek karakter için [Size] içinde Path.
  static Path pathForChar(String ch, Size size) {
    final strokes = forChar(ch) ?? _glyphs['?'];
    return PathTracingEngine.pathFromNormalized(strokes!, size);
  }

  /// Kelime: harfler yan yana; boşluk dar hücre.
  static Path pathForWord(String word, Size size) {
    final chars = word.split('').where((c) => c.trim().isNotEmpty || c == ' ').toList();
    if (chars.isEmpty) return Path();
    final n = chars.length;
    final gap = size.width * 0.02;
    final cellW = (size.width - gap * (n - 1)) / n;
    final cellH = size.height;
    final path = Path();
    for (var i = 0; i < n; i++) {
      final ch = chars[i];
      if (ch == ' ') continue;
      final strokes = forChar(ch);
      if (strokes == null) continue;
      final origin = Offset(i * (cellW + gap), 0);
      path.addPath(
        PathTracingEngine.pathFromNormalized(
          strokes,
          size,
          origin: origin,
          cell: Size(cellW * 0.9, cellH),
        ),
        Offset.zero,
      );
    }
    return path;
  }

